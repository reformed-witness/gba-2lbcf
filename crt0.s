@ GBA startup code with proper header
@---------------------------------------------------------------------------------
.section .text
.global _start
.arm

_start:
    b rom_header_end

    @ Nintendo logo (required for GBA boot)
    .byte 0x24,0xFF,0xAE,0x51,0x69,0x9A,0xA2,0x21,0x3D,0x84,0x82,0x0A,0x84,0xE4,0x09,0xAD
    .byte 0x11,0x24,0x8B,0x98,0xC0,0x81,0x7F,0x21,0xA3,0x52,0xBE,0x19,0x93,0x09,0xCE,0x20
    .byte 0x10,0x46,0x4A,0x4A,0xF8,0x27,0x31,0xEC,0x58,0xC7,0xE8,0x33,0x82,0xE3,0xCE,0xBF
    .byte 0x85,0xF4,0xDF,0x94,0xCE,0x4B,0x09,0xC1,0x94,0x56,0x8A,0xC0,0x13,0x72,0xA7,0xFC
    .byte 0x9F,0x84,0x4D,0x73,0xA3,0xCA,0x9A,0x61,0x58,0x97,0xA3,0x27,0xFC,0x03,0x98,0x76
    .byte 0x23,0x1D,0xC7,0x61,0x03,0x04,0xAE,0x56,0xBF,0x38,0x84,0x00,0x40,0xA7,0x0E,0xFD
    .byte 0xFF,0x52,0xFE,0x03,0x6F,0x95,0x30,0xF1,0x97,0xFB,0xC0,0x85,0x60,0xD6,0x80,0x25
    .byte 0xA9,0x63,0xBE,0x03,0x01,0x4E,0x38,0xE2,0xF9,0xA2,0x34,0xFF,0xBB,0x3E,0x03,0x44
    .byte 0x78,0x00,0x90,0xCB,0x88,0x11,0x3A,0x94,0x65,0xC0,0x7C,0x63,0x87,0xF0,0x3C,0xAF
    .byte 0xD6,0x25,0xE4,0x8B,0x38,0x0A,0xAC,0x72,0x21,0xD4,0xF8,0x07

    @ Game title (12 bytes, must be exactly 12)
    .ascii "CONFESSION  "
    
    @ Game code (4 bytes)  
    .ascii "AXVE"
    
    @ Maker code (2 bytes)
    .ascii "01"
    
    @ Fixed value (must be 0x96)
    .byte 0x96
    
    @ Main unit code
    .byte 0x00
    
    @ Device type  
    .byte 0x00
    
    @ Reserved area (7 bytes)
    .byte 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
    
    @ Software version
    .byte 0x00
    
    @ Complement check (will be calculated by gbafix or manually)
    .byte 0x00
    
    @ Reserved (2 bytes)
    .byte 0x00, 0x00

rom_header_end:
    @ Switch to ARM mode and set up system
    mov r0, #0x12       @ IRQ mode
    msr cpsr_c, r0
    ldr sp, =0x03007FA0 @ IRQ stack
    
    mov r0, #0x1F       @ System mode  
    msr cpsr_c, r0
    ldr sp, =0x03008000 @ User stack
    
    @ Initialize memory sections
    @ Copy .data section from ROM to RAM
    ldr r0, =__data_load
    ldr r1, =__data_start  
    ldr r2, =__data_end
    cmp r1, r2
    beq data_copy_done
data_copy_loop:
    ldr r3, [r0], #4
    str r3, [r1], #4
    cmp r1, r2
    blt data_copy_loop
data_copy_done:

    @ Clear .bss section
    ldr r0, =__bss_start
    ldr r1, =__bss_end
    mov r2, #0
    cmp r0, r1
    beq bss_clear_done
bss_clear_loop:
    str r2, [r0], #4
    cmp r0, r1
    blt bss_clear_loop
bss_clear_done:

    @ Jump to main function
    bl main
    
    @ Infinite loop if main returns
infinite_loop:
    b infinite_loop